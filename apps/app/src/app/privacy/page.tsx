'use client';

import React, { useState } from 'react';
import { useRouter } from 'next/navigation';
import {
  Frame,
  HatchOverlay,
  GlassCard,
  Button,
  Modal,
  Icon,
  KavachLogo,
} from '@kavach/ui';

export default function PrivacyRightsPage() {
  const router = useRouter();
  const [voiceDeleted, setVoiceDeleted] = useState(false);
  const [deleteModalOpen, setDeleteModalOpen] = useState(false);
  const [exportReady, setExportReady] = useState(false);

  const handleDeleteVoice = () => {
    setVoiceDeleted(true);
    setTimeout(() => {
      alert('Voice embedding vectors and pre-rendered emergency audio files permanently deleted from storage.');
    }, 200);
  };

  const handleExportData = () => {
    setExportReady(true);
    const mockExport = {
      household: 'Iyer Residence',
      elder: 'Mrs. Kamala Iyer',
      registeredDate: '2026-10-15',
      incidentsLogged: 3,
      voiceCloningActive: !voiceDeleted,
      rawAudioSaved: false,
      retentionPolicyDays: 7,
    };
    const dataStr = 'data:text/json;charset=utf-8,' + encodeURIComponent(JSON.stringify(mockExport, null, 2));
    const downloadAnchor = document.createElement('a');
    downloadAnchor.setAttribute('href', dataStr);
    downloadAnchor.setAttribute('download', 'kavach_household_export_dpdp.json');
    document.body.appendChild(downloadAnchor);
    downloadAnchor.click();
    downloadAnchor.remove();
  };

  const handlePurgeAccount = () => {
    setDeleteModalOpen(false);
    if (typeof window !== 'undefined') {
      localStorage.clear();
    }
    router.push('/auth');
  };

  return (
    <Frame withHatch={false} className="pb-16 min-h-screen">
      <HatchOverlay />

      {/* Header */}
      <header className="relative z-20 px-6 py-4 sm:px-10 flex items-center justify-between border-b border-white/10 backdrop-blur-md bg-white/[0.02]">
        <div className="flex items-center gap-4">
          <a href="/" className="flex items-center gap-2 focus:outline-none">
            <KavachLogo size={32} showWordmark={true} />
          </a>
          <span className="text-white/20">/</span>
          <span className="text-xs font-heading font-bold text-white/90">Privacy Rights &amp; Data Control</span>
        </div>

        <Button variant="ghost" size="sm" href="/" icon="arrow-left-linear">
          Dashboard
        </Button>
      </header>

      <main className="relative z-10 px-6 sm:px-10 lg:px-12 pt-8 max-w-4xl mx-auto space-y-8">
        <div className="space-y-2">
          <div className="inline-flex items-center gap-2 px-3 py-1 rounded-full border border-white/18 bg-white/5 text-xs font-mono text-white/80">
            <Icon name="shield-check-bold" size={14} color="#c8f542" />
            <span>Digital Personal Data Protection Act (DPDP 2023) Controls</span>
          </div>

          <h1 className="text-2xl sm:text-3xl font-heading font-bold text-white">
            Household Data Governance &amp; Erasure
          </h1>

          <p className="text-xs sm:text-sm text-white/60 font-body">
            You maintain absolute ownership and real-time control over all data generated by your household tablet.
          </p>
        </div>

        {/* 1-Click Voice Deletion Card */}
        <GlassCard className="p-6 sm:p-8 space-y-4 border-amber-400/30">
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 border-b border-white/10 pb-4">
            <div>
              <div className="text-xs font-mono text-amber-300 uppercase tracking-wider">
                Voice Biometric Embedding
              </div>
              <h2 className="text-lg font-heading font-bold text-white">Consented Familial Voice Profile</h2>
            </div>
            <span className="text-xs font-mono text-white/60">
              Status: {!voiceDeleted ? <strong className="text-[#c8f542]">Active</strong> : <strong className="text-[#ff5a4d]">Purged</strong>}
            </span>
          </div>

          <p className="text-xs text-white/70 font-body leading-relaxed">
            If you no longer wish for Kavach to play simulated audio in the daughter’s voice during emergency escalations, you can instantaneously erase your voice profile and all pre-rendered audio clips. Kavach will revert to our reassuring standard neutral voice.
          </p>

          <div className="pt-2">
            {!voiceDeleted ? (
              <Button
                variant="ghost"
                size="sm"
                onClick={handleDeleteVoice}
                icon="trash-bin-trash-bold"
                className="border-amber-400/30 text-amber-300 hover:bg-amber-400/10 text-xs"
              >
                1-Click Delete Voice Profile &amp; Cached Audio
              </Button>
            ) : (
              <div className="p-3 rounded-xl bg-amber-400/10 border border-amber-400/20 text-xs text-amber-300 font-mono">
                ✓ Voice profile purged. Tabletop tablet will use standard neutral synthesized speech.
              </div>
            )}
          </div>
        </GlassCard>

        {/* Data Export Card */}
        <GlassCard className="p-6 sm:p-8 space-y-4">
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 border-b border-white/10 pb-4">
            <div>
              <div className="text-xs font-mono text-[#c8f542] uppercase tracking-wider">
                Data Portability (DPDP Section 12)
              </div>
              <h2 className="text-lg font-heading font-bold text-white">Export Household Data</h2>
            </div>
            <span className="text-xs font-mono text-white/40">JSON Format</span>
          </div>

          <p className="text-xs text-white/70 font-body leading-relaxed">
            Download a complete portable archive containing all logged incident timestamps, detection scores, paired tablet device identifiers, and elder configuration records.
          </p>

          <Button
            variant="lime"
            size="sm"
            onClick={handleExportData}
            icon="download-square-bold"
            className="text-xs"
          >
            Download Machine-Readable JSON Export
          </Button>
        </GlassCard>

        {/* Total Account Purge (Danger Zone) */}
        <GlassCard className="p-6 sm:p-8 space-y-4 border-[#ff5a4d]/40 bg-[#ff5a4d]/5">
          <div className="space-y-1">
            <h2 className="text-lg font-heading font-bold text-[#ff5a4d]">
              Danger Zone: Immediate Household Data Erasure
            </h2>
            <p className="text-xs text-white/70 font-body leading-relaxed">
              Permanently terminate this household account, unlink all paired tabletop tablets, cancel any active subscriptions, and immediately purge all incident records from our servers. This action is irreversible.
            </p>
          </div>

          <div className="pt-2">
            <Button
              variant="ghost"
              size="sm"
              onClick={() => setDeleteModalOpen(true)}
              className="border-[#ff5a4d]/40 text-[#ff5a4d] hover:bg-[#ff5a4d]/10 text-xs"
              icon="shield-cross-bold"
            >
              Request Immediate Account Deletion
            </Button>
          </div>
        </GlassCard>

        {/* Delete Confirmation Modal */}
        <Modal
          isOpen={deleteModalOpen}
          onClose={() => setDeleteModalOpen(false)}
          title="Confirm Permanent Account Erasure"
        >
          <div className="space-y-4 text-xs font-body">
            <p className="text-white/80">
              Are you sure you want to permanently delete <strong>Iyer Residence</strong> and all associated elder monitoring records?
            </p>
            <div className="p-3 rounded-lg bg-[#ff5a4d]/10 border border-[#ff5a4d]/30 text-[#ff5a4d] font-mono text-[11px]">
              Warning: All paired tablets will disconnect immediately and cease scam protection.
            </div>
            <div className="flex justify-end gap-3 pt-2">
              <Button variant="ghost" size="sm" onClick={() => setDeleteModalOpen(false)}>
                Cancel
              </Button>
              <Button
                variant="lime"
                size="sm"
                onClick={handlePurgeAccount}
                className="bg-[#ff5a4d] text-white hover:bg-[#e0483c] border-[#ff5a4d]"
              >
                Yes, Purge Everything Now
              </Button>
            </div>
          </div>
        </Modal>
      </main>
    </Frame>
  );
}
