'use client';

import React, { useState } from 'react';
import { useRouter } from 'next/navigation';
import {
  Button,
  Modal,
  Icon,
  KavachLogo,
  Badge,
} from '@kavach/ui';

export default function PrivacyRightsPage() {
  const router = useRouter();
  const [voiceDeleted, setVoiceDeleted] = useState(false);
  const [deleteModalOpen, setDeleteModalOpen] = useState(false);
  const [exportReady, setExportReady] = useState(false);

  const handleDeleteVoice = () => {
    setVoiceDeleted(true);
    setTimeout(() => {
      alert('Voice embedding vectors and pre-rendered emergency audio files permanently deleted from storage.');
    }, 200);
  };

  const handleExportData = () => {
    setExportReady(true);
    const mockExport = {
      household: 'Iyer Residence',
      elder: 'Mrs. Kamala Iyer',
      registeredDate: '2026-10-15',
      incidentsLogged: 3,
      voiceCloningActive: !voiceDeleted,
      rawAudioSaved: false,
      retentionPolicyDays: 7,
    };
    const dataStr = 'data:text/json;charset=utf-8,' + encodeURIComponent(JSON.stringify(mockExport, null, 2));
    const downloadAnchor = document.createElement('a');
    downloadAnchor.setAttribute('href', dataStr);
    downloadAnchor.setAttribute('download', 'kavach_household_export_dpdp.json');
    document.body.appendChild(downloadAnchor);
    downloadAnchor.click();
    downloadAnchor.remove();
  };

  const handlePurgeAccount = () => {
    setDeleteModalOpen(false);
    if (typeof window !== 'undefined') {
      localStorage.clear();
    }
    router.push('/auth');
  };

  return (
    <div className="min-h-screen bg-canvas text-ink font-body">
      {/* Header */}
      <header className="bg-surface border-b border-hairline px-4 sm:px-6 lg:px-8 py-3.5 sticky top-0 z-40">
        <div className="max-w-7xl mx-auto flex items-center justify-between">
          <div className="flex items-center gap-3">
            <a href="/" className="flex items-center gap-2 focus:outline-none">
              <KavachLogo size={28} showWordmark={true} />
            </a>
            <span className="text-muted">/</span>
            <span className="text-ui font-heading font-bold text-ink">Privacy Rights &amp; Data Control</span>
          </div>

          <Button variant="outline-neutral" size="sm" href="/" icon="arrow-left-linear">
            Dashboard
          </Button>
        </div>
      </header>

      <main className="max-w-4xl mx-auto px-4 sm:px-6 lg:px-8 py-8 space-y-6">
        <div className="space-y-2">
          <div className="inline-flex items-center gap-2">
            <Badge variant="neutral-subtle" className="font-mono text-caption">
              <Icon name="shield-check-bold" size={14} className="text-primary mr-1" />
              Digital Personal Data Protection Act (DPDP 2023) Controls
            </Badge>
          </div>

          <h1 className="text-display font-heading font-bold text-ink">
            Household Data Governance &amp; Erasure
          </h1>

          <p className="text-ui text-body">
            You maintain absolute ownership and real-time control over all data generated by your household tablet.
          </p>
        </div>

        {/* 1-Click Voice Deletion Card */}
        <div className="bg-surface border border-hairline rounded-md p-6 sm:p-8 space-y-4 shadow-level-1">
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 border-b border-hairline pb-4">
            <div>
              <div className="text-caption font-mono text-primary uppercase tracking-wider font-bold">
                Voice Biometric Embedding
              </div>
              <h2 className="text-heading font-heading font-bold text-ink">Consented Familial Voice Profile</h2>
            </div>
            <div className="flex items-center gap-2">
              <span className="text-caption font-mono text-muted">Status:</span>
              {!voiceDeleted ? (
                <Badge variant="primary">Active</Badge>
              ) : (
                <Badge variant="hot">Purged</Badge>
              )}
            </div>
          </div>

          <p className="text-ui text-body leading-relaxed">
            If you no longer wish for Kavach to play simulated audio in the daughter’s voice during emergency escalations, you can instantaneously erase your voice profile and all pre-rendered audio clips. Kavach will revert to our reassuring standard neutral voice.
          </p>

          <div className="pt-2">
            {!voiceDeleted ? (
              <Button
                variant="outline-neutral"
                size="sm"
                onClick={handleDeleteVoice}
                icon="trash-bin-trash-bold"
              >
                1-Click Delete Voice Profile &amp; Cached Audio
              </Button>
            ) : (
              <div className="p-3.5 rounded-md bg-canvas border border-hairline text-caption text-body font-mono">
                ✓ Voice profile purged. Tabletop tablet will use standard neutral synthesized speech.
              </div>
            )}
          </div>
        </div>

        {/* Data Export Card */}
        <div className="bg-surface border border-hairline rounded-md p-6 sm:p-8 space-y-4 shadow-level-1">
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 border-b border-hairline pb-4">
            <div>
              <div className="text-caption font-mono text-primary uppercase tracking-wider font-bold">
                Data Portability (DPDP Section 12)
              </div>
              <h2 className="text-heading font-heading font-bold text-ink">Export Household Data</h2>
            </div>
            <span className="text-caption font-mono text-muted">JSON Format</span>
          </div>

          <p className="text-ui text-body leading-relaxed">
            Download a complete portable archive containing all logged incident timestamps, detection scores, paired tablet device identifiers, and elder configuration records.
          </p>

          <Button
            variant="primary"
            size="sm"
            onClick={handleExportData}
            icon="download-square-bold"
          >
            Download Machine-Readable JSON Export
          </Button>
        </div>

        {/* Total Account Purge (Danger Zone) */}
        <div className="bg-surface border border-hairline rounded-md p-6 sm:p-8 space-y-4 shadow-level-1">
          <div className="space-y-1">
            <h2 className="text-heading font-heading font-bold text-hot">
              Danger Zone: Immediate Household Data Erasure
            </h2>
            <p className="text-ui text-body leading-relaxed">
              Permanently terminate this household account, unlink all paired tabletop tablets, cancel any active subscriptions, and immediately purge all incident records from our servers. This action is irreversible.
            </p>
          </div>

          <div className="pt-2">
            <button
              onClick={() => setDeleteModalOpen(true)}
              className="inline-flex items-center gap-2 px-4 py-2 rounded-full border border-hot text-hot text-ui font-bold hover:bg-hot/10 transition-colors"
            >
              <Icon name="shield-cross-bold" size={16} />
              <span>Request Immediate Account Deletion</span>
            </button>
          </div>
        </div>

        {/* Delete Confirmation Modal */}
        <Modal
          isOpen={deleteModalOpen}
          onClose={() => setDeleteModalOpen(false)}
          title="Confirm Permanent Account Erasure"
        >
          <div className="space-y-4 text-ui font-body">
            <p className="text-body">
              Are you sure you want to permanently delete <strong>Iyer Residence</strong> and all associated elder monitoring records?
            </p>
            <div className="p-3.5 rounded-md bg-canvas border border-hairline text-hot font-mono text-caption font-bold">
              Warning: All paired tablets will disconnect immediately and cease scam protection.
            </div>
            <div className="flex justify-end gap-3 pt-2">
              <Button variant="outline-neutral" size="sm" onClick={() => setDeleteModalOpen(false)}>
                Cancel
              </Button>
              <button
                onClick={handlePurgeAccount}
                className="px-4 py-2 rounded-full bg-hot text-on-primary font-bold text-ui hover:opacity-90 transition-opacity"
              >
                Yes, Purge Everything Now
              </button>
            </div>
          </div>
        </Modal>
      </main>
    </div>
  );
}

